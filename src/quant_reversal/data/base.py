from datetime import date
from typing import Protocol, Sequence
import pandas as pd
class DataProvider(Protocol):
    def get_trading_calendar(self, start: date, end: date) -> pd.DataFrame: ...
    def get_daily_bars(self, start: date, end: date, symbols: Sequence[str] | None = None) -> pd.DataFrame: ...
    def get_auction(self, start: date, end: date, symbols: Sequence[str] | None = None) -> pd.DataFrame: ...
    def get_minute_bars(self, trade_date: date, symbols: Sequence[str] | None = None) -> pd.DataFrame: ...
    def get_sector_membership(self, trade_date: date, symbols: Sequence[str] | None = None) -> pd.DataFrame: ...
    def get_index_daily(self, start: date, end: date) -> pd.DataFrame: ...
    def get_index_auction(self, trade_date: date) -> pd.DataFrame: ...

